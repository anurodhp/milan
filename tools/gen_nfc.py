#!/usr/bin/env python3 -I
"""Generates MilanNFC_tables.h: the canonical composition pairs and combining classes (BMP) that MilanNFC.m needs,
because this GNUstep base is built without ICU (precomposedStringWithCanonicalMapping is not implemented).
Run on the host: python3 -I tools/gen_nfc.py > MilanNFC_tables.h"""
import sys, unicodedata

pairs = []
for c in range(0x10000):
    if 0xD800 <= c < 0xE000:
        continue
    d = unicodedata.decomposition(chr(c))
    if not d or d.startswith('<'):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) != 2 or parts[0] > 0xFFFF or parts[1] > 0xFFFF:
        continue
    if unicodedata.normalize('NFC', chr(parts[0]) + chr(parts[1])) != chr(c):
        continue                                   # composition exclusion
    pairs.append((parts[0], parts[1], c))
pairs.sort()
ccc = [(c, unicodedata.combining(chr(c))) for c in range(0x10000)
       if not 0xD800 <= c < 0xE000 and unicodedata.combining(chr(c))]
w = sys.stdout.write
w('/* generated by tools/gen_nfc.py (Unicode %s); do not edit */\n' % unicodedata.unidata_version)
w('static const unsigned short nfcPairs[][3] = {\n')
for a, b, c in pairs:
    w('\t{ 0x%04X, 0x%04X, 0x%04X },\n' % (a, b, c))
w('};\nstatic const unsigned short nfcClasses[][2] = {\n')
for c, k in ccc:
    w('\t{ 0x%04X, %d },\n' % (c, k))
w('};\n')
